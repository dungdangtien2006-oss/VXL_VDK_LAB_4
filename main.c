void Task_2_5s(void) { HAL_GPIO_TogglePin(LED5_GPIO_Port, LED5_Pin); }

// ---- Timestamp callbacks ----
// Fires every CALLBACK_PERIOD_MS (10 ms) and prints get_time()
void Task_10ms(void) {
    printf("[10ms]  t = %lu ms\r\n", (unsigned long)get_time());
}

// Second timeout with a different interval (500 ms), running concurrently
void Task_500ms(void) {
    printf("[500ms] t = %lu ms\r\n", (unsigned long)get_time());
}

// One-shot callbacks registered before the main loop; print time when delay expires
void Task_Wake1(void) {
    printf("[wake1] fired at t = %lu ms\r\n", (unsigned long)get_time());
}
void Task_Wake2(void) {
    printf("[wake2] fired at t = %lu ms\r\n", (unsigned long)get_time());
}
void Task_Wake3(void) {
    printf("[wake3] fired at t = %lu ms\r\n", (unsigned long)get_time());
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance == TIM2) {
        sch_time_ms += TICK;
        SCH_Update();
    }
}
