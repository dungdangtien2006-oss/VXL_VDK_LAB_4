// ---- 5 LED tasks: 0.5s, 1s, 1.5s, 2s, 2.5s ----
void Task_0_5s(void) { HAL_GPIO_TogglePin(LED1_GPIO_Port, LED1_Pin); }
void Task_1_0s(void) { HAL_GPIO_TogglePin(LED2_GPIO_Port, LED2_Pin); }
void Task_1_5s(void) { HAL_GPIO_TogglePin(LED3_GPIO_Port, LED3_Pin); }
